import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: ["src/app/beam-runtime-entry.ts"], bundle: true, write: false,
  format: "iife", globalName: "NodeBeam", target: "es2020", minify: true,
});
await writeFile("src/app/beam-runtime-source.ts", `// Generated by scripts/build-beam-handoff-runtime.mjs from the shared painter.\nexport const beamRuntimeSource = ${JSON.stringify(result.outputFiles[0].text)};\n`);
console.log("Built developer renderer from the canonical beam painter.");
